from fastapi import APIRouter, Query, Response
from datetime import datetime, timezone
from app.services.dns_engine import DNSEngine
from app.services.ssl_engine import SSLEngine
from app.services.headers_engine import HeadersEngine
from app.services.whois_engine import WhoisEngine

router = APIRouter(prefix="/api/recon", tags=["Reporting & Export"])

@router.get("/export-dossier")
async def export_dossier(domain: str = Query(..., description="Target domain")):
    clean = domain.strip().lower().replace("https://", "").replace("http://", "").split("/")[0].split(":")[0]

    dns_data = DNSEngine.resolve_domain(clean)
    ssl_data = SSLEngine.inspect(clean)
    headers_data = await HeadersEngine.analyze(clean)
    whois_data = WhoisEngine.lookup(clean)
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    md = f"""# EXECUTIVE ATTACK SURFACE DOSSIER
**Target:** `{clean}`  
**Generated On:** `{now_str}`  
**Tool:** Vatsal's SecOps Reconnaissance & Attack Surface Console 2.0  

---

## 1. Executive Summary & Posture Grade
- **Defensive Posture Score:** **{headers_data.get('posture_score', 0)} / 100**
- **Security Grade:** **{headers_data.get('posture_grade', 'F')}**
- **Edge Shield / WAF:** {headers_data.get('detected_waf', 'None Detected')}
- **TLS Status:** {ssl_data.get('status', 'Unknown')} ({ssl_data.get('tls_version', 'N/A')})

---

## 2. Infrastructure & Registry Intel
- **Registrar:** {whois_data.get('registrar', 'Unknown')}
- **Creation Date:** {whois_data.get('creation_date', 'N/A')}
- **Registry Expiry:** {whois_data.get('expiration_date', 'N/A')}
- **Name Servers:** {', '.join(whois_data.get('name_servers', [])) or 'N/A'}

---

## 3. DNS Record Discovery
"""
    for rtype, records in dns_data.get("records", {}).items():
        md += f"### {rtype} Records ({len(records)})\n"
        for r in records:
            md += f"- `{r}`\n"
        md += "\n"

    if dns_data.get("dangling_cnames"):
        md += "### ⚠️ CRITICAL DANGLING CNAME FINDINGS\n"
        for d in dns_data["dangling_cnames"]:
            md += f"- **CNAME:** `{d['cname']}` | **Provider:** {d['provider']} | **Severity:** {d['severity']}\n"
        md += "\n"

    md += f"""---

## 4. Cryptographic & TLS Configuration
- **Subject:** `{ssl_data.get('subject_cn', 'N/A')}`
- **Issuer:** {ssl_data.get('issuer_org', 'N/A')} ({ssl_data.get('issuer_cn', 'N/A')})
- **Valid Until:** {ssl_data.get('valid_until', 'N/A')} ({ssl_data.get('days_remaining', 0)} days left)
- **Negotiated Cipher:** `{ssl_data.get('cipher_suite', 'N/A')}`
- **Wildcard Certificate:** {'Yes (*.domain)' if ssl_data.get('is_wildcard') else 'No'}

---

## 5. HTTP Defensive Headers Audit
"""
    for finding in headers_data.get("detailed_findings", []):
        badge = "✅ PASS" if finding["status"] == "PASS" else ("⚠️ WARN" if finding["status"] == "WARN" else "❌ FAIL")
        md += f"- **{badge} - {finding['header']}:** `{finding['value']}`\n  *{finding['importance']}*\n"

    md += """
---
*Confidential Security Assessment Document • Generated by Vatsal's SecOps Toolkit*
"""

    filename = f"secops_dossier_{clean}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.md"
    return Response(
        content=md,
        media_type="text/markdown",
        headers={"Content-Disposition": f"attachment; filename={filename}"}
    )
